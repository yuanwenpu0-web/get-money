"""Explicit name-to-function bindings for ported indicators.

Only registered implementations can be invoked; catalog source is never executed.
The allowlist lives in `_table.py`, generated by `scripts/sync_catalog_registry.py`
from the port manifest: every row pins the collection, the Pine path and the
SHA-256 of that file, so a binding silently drops out as soon as the upstream
source changes.
"""
from __future__ import annotations

import importlib
from dataclasses import dataclass
from typing import Callable

import pandas as pd

from ._table import ROWS


@dataclass(frozen=True)
class Indicator:
    name: str
    collection: str
    path: str
    source_sha256: str
    calculate: Callable[..., pd.DataFrame]


def _bind(name: str, collection: str, path: str, source_sha256: str) -> Indicator:
    module = importlib.import_module(f".{name}", __package__)
    function = getattr(module, name)
    return Indicator(name, collection, path, source_sha256, function)


_INDICATORS = {name: _bind(name, collection, path, sha) for name, collection, path, sha in ROWS}


def list_indicators() -> tuple[Indicator, ...]:
    return tuple(_INDICATORS.values())


def get_indicator(name: str) -> Indicator:
    try:
        return _INDICATORS[name]
    except (KeyError, TypeError):
        raise ValueError(f"未知或尚未移植的指标方法: {name}") from None


def calculate(name: str, frame: pd.DataFrame, **params) -> pd.DataFrame:
    return get_indicator(name).calculate(frame, **params)
