"""Regenerate `app/catalog_indicators/_table.py` from the port manifest.

The catalog registry stays an explicit allowlist: a module is only reachable
when its row is written here, and every row carries the SHA-256 of the Pine
source it was ported from, so `_catalog()` can refuse a binding as soon as the
upstream file changes.

Usage:
    python scripts/sync_catalog_registry.py            # merge, keep existing rows
    python scripts/sync_catalog_registry.py --check    # fail if the table is stale
"""
from __future__ import annotations

import argparse
import hashlib
import json
import pathlib
import re
import sys

BACKEND = pathlib.Path(__file__).resolve().parents[1]
ROOT = BACKEND.parent
PACKAGE = BACKEND / "app" / "catalog_indicators"
TABLE = PACKAGE / "_table.py"
MANIFEST = ROOT / ".workbuddy" / "port_manifest.json"

ROW = re.compile(r'\("(?P<name>[a-z0-9_]+)",\s*"(?P<collection>[a-z\-]+)",\s*'
                 r'"(?P<path>[^"]+)",\s*"(?P<sha>[0-9a-f]{64})"\)')


def read_rows() -> dict[str, tuple[str, str, str]]:
    """Rows already recorded, keyed by module name."""
    if not TABLE.is_file():
        return {}
    text = TABLE.read_text(encoding="utf-8")
    return {match["name"]: (match["collection"], match["path"], match["sha"])
            for match in ROW.finditer(text)}


def source_sha256(collection: str, path: str) -> str:
    return hashlib.sha256((ROOT / "data" / collection / path).read_bytes()).hexdigest()


def write_table(rows: dict[str, tuple[str, str, str]]) -> None:
    ordered = sorted(rows.items(), key=lambda item: (item[1][0], item[1][1]))
    lines = ['"""Generated by scripts/sync_catalog_registry.py — do not edit by hand.',
             "",
             "Each row is (module name, collection, source path, source SHA-256). The module",
             "name doubles as the public function name and the registry key.",
             '"""',
             "from __future__ import annotations",
             "",
             "ROWS: tuple[tuple[str, str, str, str], ...] = ("]
    for name, (collection, path, sha) in ordered:
        lines.append(f'    ("{name}", "{collection}", "{path}", "{sha}"),')
    lines.append(")")
    lines.append("")
    TABLE.write_text("\n".join(lines), encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="only report a stale table")
    options = parser.parse_args()

    rows = read_rows()
    before = dict(rows)
    missing: list[str] = []
    manifest = json.loads(MANIFEST.read_text(encoding="utf-8")) if MANIFEST.is_file() else []
    existing = {path.stem for path in PACKAGE.glob("*.py") if not path.stem.startswith("_")}
    renamed: dict[str, str] = {}
    if MANIFEST.is_file():
        for entry in manifest:
            name = entry["module"]
            if not (PACKAGE / f"{name}.py").is_file():
                # A ported module may drop the trailing version suffix the manifest kept
                # (e.g. `capital41_adx_filter` for `capital41_adx_filter_v3`).
                shorter = sorted(candidate for candidate in existing
                                 if name.startswith(candidate) and len(candidate) >= len(name) - 6)
                if len(shorter) == 1:
                    entry["module"], name = shorter[0], shorter[0]
                    renamed[name] = name
                else:
                    missing.append(name)
                    continue
            source = ROOT / "data" / entry["collection"] / entry["path"]
            if not source.is_file():
                raise SystemExit(f"缺少源文件: {entry['collection']}/{entry['path']}")
            rows[name] = (entry["collection"], entry["path"], source_sha256(entry["collection"], entry["path"]))
    # Keep rows whose module still exists even when the manifest no longer lists them.
    rows = {name: value for name, value in rows.items() if (PACKAGE / f"{name}.py").is_file()}

    if options.check:
        if rows != before:
            print(f"表已过期：新增 {sorted(set(rows) - set(before))}", file=sys.stderr)
            return 1
        print(f"表是最新的：{len(rows)} 个绑定")
        return 0

    write_table(rows)
    if renamed:
        MANIFEST.write_text(json.dumps(manifest, ensure_ascii=False, indent=1), encoding="utf-8")
        print(f"清单模块名对齐 {len(renamed)} 个：{', '.join(sorted(renamed))}")
    added = sorted(set(rows) - set(before))
    print(f"绑定 {len(rows)} 个；本批新增 {len(added)} 个：{', '.join(added) if added else '无'}")
    if missing:
        print(f"清单中尚未落地的模块 {len(missing)} 个")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
